#!/usr/bin/env bash
# Regenera THIRD_PARTY_LICENSES: el texto de licencia (y NOTICE) de Go y de cada módulo compilado en los binarios.
# Correr tras cambiar go.mod; tools/packaging/notice_test.go falla si falta un módulo.
set -euo pipefail
cd "$(dirname "$0")/../.."
# Mismo resultado en cualquier máquina: orden por bytes y la plataforma que se empaqueta.
export LC_ALL=C GOOS=linux
shopt -s nullglob nocaseglob
fmt='{{with .Module}}{{if not .Main}}{{.Path}} {{.Dir}}{{end}}{{end}}'
# -e en ./ui: sin la UI compilada el //go:embed de frontend/dist falla, pero las dependencias son las mismas.
mods=$( { go list -deps -f "$fmt" ./cmd/...; go list -e -tags 'wails gtk3' -deps -f "$fmt" ./ui; } | sort -u)
seccion() { # nombre carpeta
  local files=("$2"/{LICEN[CS]E,COPYING,NOTICE}*)
  ((${#files[@]})) || { echo "no license file: $1 ($2)" >&2; exit 1; }
  printf '\n\n======== %s ========\n' "$1"
  for p in "${files[@]}"; do
    printf '\n--- %s ---\n\n' "${p##*/}"
    cat "$p"
  done
}
{
  echo "Licenses of Go and of the modules compiled into macuahuitld, mctl and macuahuitl."
  echo "The JavaScript libraries of the interface are listed in NOTICE. Generated by tools/packaging/third-party-licenses.sh."
  seccion "Go (runtime and standard library)" "$(go env GOROOT)"
  while read -r path dir; do seccion "$path" "$dir"; done <<< "$mods"
} > THIRD_PARTY_LICENSES
echo "THIRD_PARTY_LICENSES: Go and $(wc -l <<< "$mods") modules"
